def build_ppt():
    prs = Presentation(PPT_SRC)
    slides = list(prs.slides)
    assert len(slides) == len(SCRIPT), (len(slides), len(SCRIPT))
    for no, edits in PPT_EDITS.items():
        for old, new in edits:
            set_par(slides[no - 1], old, new)
    for sl, (_, _, t) in zip(slides, SCRIPT):
        tf = sl.notes_slide.notes_text_frame
        if tf is not None:          # 부록(20쪽)은 노트 칸이 없는 슬라이드 — 대본 문서에만 넣는다
            tf.text = t
    prs.save(PPT_DST)


