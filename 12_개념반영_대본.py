def build_docx():
    doc = Document()
    st = doc.styles["Normal"]
    st.font.name = "맑은 고딕"
    st.element.rPr.rFonts.set(qn("w:eastAsia"), "맑은 고딕")
    st.font.size = Pt(11)
    h = doc.add_paragraph()
    r = h.add_run("「한눈」 발표 대본")
    r.bold, r.font.size = True, Pt(18)
    doc.add_paragraph("2026 HUSS · AI를 활용한 어울림 공모전 / 발표 김성빈 / 슬라이드 20장, 약 7~8분(시연 영상 제외)").runs[0].font.color.rgb = RGBColor(0x6B, 0x76, 0x84)
    for i, (title, sec, text) in enumerate(SCRIPT, 1):
        p = doc.add_paragraph()
        p.paragraph_format.space_before = Pt(12)
        r = p.add_run("{}. {}".format(i, title))
        r.bold, r.font.size = True, Pt(13)
        r2 = p.add_run("   {}".format(sec))
        r2.font.size, r2.font.color.rgb = Pt(10), RGBColor(0x31, 0x82, 0xF6)
        q = doc.add_paragraph(text)
        q.paragraph_format.line_spacing = 1.5
        q.alignment = WD_ALIGN_PARAGRAPH.LEFT
    doc.save(DOCX)


def backup(path):
    """덮어쓰기 전에 지금 파일을 output/_자동백업/에 시각을 붙여 남긴다(사용자가 그사이 고쳤을 수 있으므로)."""
    import datetime
    import shutil
    if os.path.exists(path):
        d = os.path.join(OUT, "_자동백업")
        os.makedirs(d, exist_ok=True)
        stem, ext = os.path.splitext(os.path.basename(path))
        shutil.copy2(path, os.path.join(d, "{}_{}{}".format(stem, datetime.datetime.now().strftime("%m%d_%H%M%S"), ext)))


